"""ERP write-back adapter.

Purchase orders, expedite requests and transfers are persisted locally (the system of record for this
service) and, when ERP_WEBHOOK_URL is set, pushed to the external ERP.

Delivery guarantees
  * Idempotency: every request carries ``Idempotency-Key: <po_number>`` (and the PO number as an external id),
    so a retry after a timeout can never create a second purchase order in an ERP that honours it.
  * Retries: transient failures (timeouts, 429, 5xx) are retried inline with exponential backoff
    (ERP_MAX_ATTEMPTS). If the ERP is still unreachable the PO is left ``erp_status="pending"`` (an outbox row)
    and the worker's background loop keeps retrying until ERP_RETRY_MAX_TOTAL_ATTEMPTS, then marks it ``failed``
    and alerts planners. Permanent 4xx responses fail immediately.
  * Mapping: ERP_FLAVOR selects the payload shape: ``generic`` (flat JSON), ``sap`` (S/4HANA purchase-order
    OData-style body) or ``netsuite`` (REST record body). The sap/netsuite templates are starting points:
    adapt the field names to your tenant's configuration.
"""
import logging
import time
import uuid

import httpx
from sqlalchemy import select
from sqlalchemy.orm import Session

from app.config import settings
from app.metrics import ERP_SYNC
from app.models import PurchaseOrder, Warehouse

log = logging.getLogger(__name__)
RETRYABLE_STATUS = {408, 425, 429, 500, 502, 503, 504}


def _po_number(kind: str) -> str:
    prefix = {"purchase": "PO", "expedite": "EXP", "transfer": "TRF"}[kind]
    return f"{prefix}-{uuid.uuid4().hex[:8].upper()}"


# ---------------------------------------------------------------------------------------------- mappings
def _generic(po: PurchaseOrder, session: Session) -> dict:
    return {"po_number": po.po_number, "kind": po.kind, "supplier_id": po.supplier_id, "product_id": po.product_id,
            "warehouse_id": po.warehouse_id, "source_warehouse_id": po.source_warehouse_id,
            "quantity": po.quantity, "unit_price": po.unit_price, "total_cost": po.total_cost}


def _sap(po: PurchaseOrder, session: Session) -> dict:
    return {
        "PurchaseOrderType": "UB" if po.kind == "transfer" else "NB",  # UB = stock transport order
        "PurchaseOrderByCustomer": po.po_number,
        "Supplier": po.supplier.name if po.supplier else "",
        "DocumentCurrency": "USD",
        "to_PurchaseOrderItem": [{
            "PurchaseOrderItem": "10", "Material": po.product.sku,
            "Plant": po.warehouse.code if po.warehouse else "",
            "OrderQuantity": str(po.quantity), "NetPriceAmount": str(po.unit_price),
            "SupplyingPlant": _wh_code(session, po.source_warehouse_id),
        }],
    }


def _netsuite(po: PurchaseOrder, session: Session) -> dict:
    return {
        "externalId": po.po_number,
        "memo": f"Auto-generated by Disruption Agent ({po.kind})",
        "entity": {"refName": po.supplier.name if po.supplier else "Internal transfer"},
        "location": {"refName": po.warehouse.code if po.warehouse else ""},
        "item": {"items": [{"item": {"refName": po.product.sku}, "quantity": po.quantity, "rate": po.unit_price}]},
    }


MAPPERS = {"generic": _generic, "sap": _sap, "netsuite": _netsuite}


def _wh_code(session: Session, warehouse_id: int | None) -> str:
    wh = session.get(Warehouse, warehouse_id) if warehouse_id else None
    return wh.code if wh else ""


def build_payload(po: PurchaseOrder, session: Session) -> dict:
    return MAPPERS.get(settings.erp_flavor, _generic)(po, session)


# ---------------------------------------------------------------------------------------------- delivery
def _headers(po: PurchaseOrder) -> dict:
    headers = {"Idempotency-Key": po.po_number, "Content-Type": "application/json"}
    if settings.erp_auth_value:
        headers[settings.erp_auth_header] = settings.erp_auth_value
    return headers


def _extract_ref(resp: httpx.Response) -> str:
    if "json" not in resp.headers.get("content-type", ""):
        return ""
    body = resp.json()
    if isinstance(body, dict):
        for key in ("id", "PurchaseOrder", "internalId", "po_id"):
            if body.get(key):
                return str(body[key])
        if isinstance(body.get("d"), dict):  # SAP OData v2 envelope
            return str(body["d"].get("PurchaseOrder", ""))
    return ""


def push_to_erp(po: PurchaseOrder, session: Session, *, attempts: int | None = None,
                sleep=None) -> bool:
    """Send one PO. Returns True when the ERP accepted it; updates the PO's sync fields either way."""
    if not settings.erp_webhook_url:
        po.erp_status = "not_configured"
        return False
    attempts = attempts or settings.erp_max_attempts
    sleep = sleep or time.sleep
    payload = build_payload(po, session)
    for attempt in range(attempts):
        po.erp_attempts = (po.erp_attempts or 0) + 1
        try:
            resp = httpx.post(settings.erp_webhook_url, json=payload, headers=_headers(po), timeout=15)
            if resp.status_code in RETRYABLE_STATUS:
                raise httpx.HTTPStatusError(f"retryable {resp.status_code}", request=resp.request, response=resp)
            resp.raise_for_status()
            po.erp_ref, po.erp_status, po.erp_last_error = _extract_ref(resp), "synced", ""
            ERP_SYNC.labels("ok").inc()
            return True
        except httpx.HTTPStatusError as exc:
            po.erp_last_error = str(exc)[:500]
            if exc.response.status_code not in RETRYABLE_STATUS:  # permanent client error: don't hammer the ERP
                po.erp_status = "failed"
                ERP_SYNC.labels("failed").inc()
                log.error("ERP rejected %s permanently: %s", po.po_number, exc)
                return False
        except Exception as exc:  # timeouts, connection errors
            po.erp_last_error = str(exc)[:500]
        ERP_SYNC.labels("retry").inc()
        if attempt < attempts - 1:
            sleep(min(30, 0.5 * 2 ** attempt))
    po.erp_status = "pending"
    log.warning("ERP unreachable for %s after %d attempts; queued for background retry", po.po_number, attempts)
    return False


def retry_pending(session: Session, sleep=None) -> dict:
    """Background outbox sweep: one attempt per pending PO; gives up after ERP_RETRY_MAX_TOTAL_ATTEMPTS."""
    from app.services.notifications import notify

    stats = {"synced": 0, "still_pending": 0, "failed": 0}
    for po in session.scalars(select(PurchaseOrder).where(PurchaseOrder.erp_status == "pending")
                              .order_by(PurchaseOrder.id).limit(50)).all():
        if push_to_erp(po, session, attempts=1, sleep=sleep):
            stats["synced"] += 1
        elif po.erp_status == "pending" and po.erp_attempts >= settings.erp_retry_max_total_attempts:
            po.erp_status = "failed"
            stats["failed"] += 1
            notify(session, f"ERP sync failed: {po.po_number}",
                   f"{po.po_number} could not be written to the ERP after {po.erp_attempts} attempts: "
                   f"{po.erp_last_error}. Create it manually.", level="critical", disruption_id=po.disruption_id)
        elif po.erp_status == "failed":
            stats["failed"] += 1
        else:
            stats["still_pending"] += 1
    return stats


def create_order(session: Session, *, kind: str, product_id: int, quantity: float, unit_price: float,
                 total_cost: float, expected_days: float, disruption_id: int,
                 supplier_id: int | None = None, warehouse_id: int | None = None,
                 source_warehouse_id: int | None = None) -> PurchaseOrder:
    po = PurchaseOrder(
        po_number=_po_number(kind), kind=kind, supplier_id=supplier_id, product_id=product_id,
        warehouse_id=warehouse_id, source_warehouse_id=source_warehouse_id, quantity=round(quantity),
        unit_price=round(unit_price, 4), total_cost=round(total_cost, 2), expected_days=expected_days,
        disruption_id=disruption_id, status="submitted",
        erp_status="pending" if settings.erp_webhook_url else "not_configured",
    )
    session.add(po)
    session.flush()
    session.refresh(po)  # load relationships used by the mappers
    push_to_erp(po, session)
    return po
